#!/usr/bin/env node
// Compile the JSON Schema into standalone JavaScript so the installed skill needs
// no runtime dependencies at all. This mirrors archify: ajv is a development
// dependency only, and the generated module is committed.
//
//   node scripts/generate-validators.mjs           write renderers/shared/generated-validators.mjs
//   node scripts/generate-validators.mjs --check   fail if the committed output is stale
//
// A stale committed validator is a real hazard: the schema would say one thing and
// the shipped skill would enforce another, so `npm test` runs the --check form.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const schemaPath = path.join(root, 'schemas', 'hydraulic-circuit.schema.json');
const outputPath = path.join(root, 'renderers', 'shared', 'generated-validators.mjs');

const HEADER = [
  '// Generated by scripts/generate-validators.mjs. Do not edit by hand.',
  '// Regenerate with: npm run generate:validators',
  '',
].join('\n');

async function loadAjv() {
  try {
    const [{ default: Ajv2020 }, { default: standaloneCode }] = await Promise.all([
      import('ajv/dist/2020.js'),
      import('ajv/dist/standalone/index.js'),
    ]);
    return { Ajv2020, standaloneCode };
  } catch (error) {
    console.error('ajv is a development dependency and is not installed.');
    console.error('Run `npm install` in the skill directory, then retry.');
    console.error(`Original error: ${error.message}`);
    process.exit(2);
  }
}

// ajv's standalone output reaches back into the installed package for one string
// helper. Left alone that would make the "zero runtime dependencies" claim false:
// the skill would work here and fail on a bare copy. Inline it and then assert no
// require survives, so the claim is enforced rather than assumed.
// This technique is taken from archify's scripts/generate-validators.mjs (MIT).
const AJV_UCS2_IMPORT = 'require("ajv/dist/runtime/ucs2length").default';
const INLINE_UCS2_LENGTH = `function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length += 1;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len
      && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos += 1;
  }
  return length;
}`;

function buildSource(Ajv2020, standaloneCode) {
  const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: true },
    allErrors: true,
    strict: false,
  });
  const validate = ajv.compile(schema);
  let code = standaloneCode(ajv, validate);

  if (code.includes(AJV_UCS2_IMPORT)) {
    code = code.replaceAll(AJV_UCS2_IMPORT, INLINE_UCS2_LENGTH);
  }
  if (code.includes('require(')) {
    const sample = code.match(/require\([^)]*\)/)?.[0];
    throw new Error(
      `ajv standalone output contains an unexpected runtime dependency: ${sample}. `
      + 'Inline it in scripts/generate-validators.mjs before committing, or the skill '
      + 'will fail on any copy without node_modules.',
    );
  }
  return `${HEADER}${code}`;
}

function normalize(text) {
  // The repository is LF everywhere (.gitattributes); compare on that basis so a
  // CRLF checkout cannot make a fresh generation look stale.
  return text.replace(/\r\n/g, '\n');
}

const { Ajv2020, standaloneCode } = await loadAjv();
const source = normalize(buildSource(Ajv2020, standaloneCode));

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath)) {
    console.error(`Missing ${path.relative(root, outputPath)}. Run: npm run generate:validators`);
    process.exit(1);
  }
  const committed = normalize(fs.readFileSync(outputPath, 'utf8'));
  if (committed !== source) {
    console.error('Committed validator is stale relative to schemas/hydraulic-circuit.schema.json.');
    console.error('Run: npm run generate:validators');
    process.exit(1);
  }
  console.log('validators up to date');
  process.exit(0);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, source, 'utf8');
console.log(`${path.relative(root, outputPath)} (${source.length} bytes)`);
